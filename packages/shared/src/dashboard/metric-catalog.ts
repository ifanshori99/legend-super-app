// Metric registry rows the dashboards and the 100+ report catalog cite (WS-11
// CT, bead legend-mmjb; PRD v1.7 §5 "Lapisan metrik baku", §6 J
// metric_definitions, DASH-01). The registry is global: one definition per
// metric code, read by dashboards, reports, the report builder, Tanya AI and
// MCP (WS-12). The 16 metrics in `@starter/shared/metrics` keep their codes;
// this file adds the ones the dashboard tiles and standard reports need, with
// the same schema and the same Cafe Legend conventions (whole-rupiah `Idr`,
// Decimal4 percentages, business dates).
//
// Every definition names its source report; the route is derived from the
// report code (`reportRouteForCode`), so a tile drill-down and a report route
// can never disagree (DASH-01/DASH-02).

import {
  cafeLegendMetricDefinitions,
  metricDefinitionSchema,
  type MetricAggregation,
  type MetricDefinition,
  type MetricDimensionKey,
  type MetricGrain,
  type MetricOfficiality,
  type MetricOwnerModule,
  type MetricUnit,
  type ReportCode,
} from "../metrics/index.ts";
import { reportRouteForCode } from "./reports.ts";

const EFFECTIVE_FROM = "2026-01-01";
const TIMESTAMP = "2026-10-20T03:15:00.000Z";

type MetricSeed = {
  id: string;
  code: string;
  version?: number;
  name: string;
  description: string;
  ownerModule: MetricOwnerModule;
  formulaRef: string;
  expression: string;
  inputs?: readonly string[];
  unit: MetricUnit;
  aggregation: MetricAggregation;
  dimensions: readonly MetricDimensionKey[];
  grain: MetricGrain;
  officiality: MetricOfficiality;
  reportCode: ReportCode;
};

function defineMetric(seed: MetricSeed): MetricDefinition {
  return metricDefinitionSchema.parse({
    id: seed.id,
    code: seed.code,
    version: seed.version ?? 1,
    name: seed.name,
    description: seed.description,
    ownerModule: seed.ownerModule,
    formula: {
      formulaRef: seed.formulaRef,
      expression: seed.expression,
      inputs: seed.inputs ?? [],
    },
    unit: seed.unit,
    aggregation: seed.aggregation,
    dimensions: [...seed.dimensions],
    grain: seed.grain,
    officiality: seed.officiality,
    sourceReport: {
      reportCode: seed.reportCode,
      route: reportRouteForCode(seed.reportCode),
    },
    status: "active",
    effectiveFrom: EFFECTIVE_FROM,
    createdAt: TIMESTAMP,
    updatedAt: TIMESTAMP,
  });
}


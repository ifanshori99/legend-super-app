type Code = { id: string; providerRef: string; linkId: string };

/** A fresh bill with one pending QRIS code. */
async function newCode(): Promise<Code> {
  const opened = await createPaymentLink(
    outletContext([outletId]),
    {
      outletId,
      reference: `R1020-${unique()}`,
      tableLabel: "A06",
      pax: 2,
      subtotalIdr: 125_000,
      discountIdr: 0,
      serviceChargeIdr: 6_250,
      taxIdr: 13_125,
      roundingIdr: 0,
      totalIdr: BILL_TOTAL,
      returnPath: "/t/v1.abc",
    },
    "00000000-0000-4000-8000-000000000001",
  );
  createdLinkIds.push(opened.linkId);
  const created = await agent(app)
    .post(`/api/payments/links/${opened.token}/intents`)
    .send({
      method: "qris",
      channelCode: null,
      idempotencyKey: `k-${unique()}`,
    });
  expect(created.status, JSON.stringify(created.body)).toBe(201);
  const id = created.body.data.id as string;
  const { rows } = await owner.query<{ provider_ref: string | null }>(
    "SELECT provider_ref FROM payment_intents WHERE id = $1",
    [id],
  );
  if (!rows[0]?.provider_ref) throw new Error("Intent has no DOIT payment id");
  return { id, providerRef: rows[0].provider_ref, linkId: opened.linkId };
}

function signatureHeader(raw: string): string {
  const t = Math.floor(Date.now() / 1000);
  const mac = createHmac("sha256", secret).update(`${t}.${raw}`).digest("hex");
  return `t=${t},v1=${mac}`;
}

async function deliver(body: object) {
  const raw = JSON.stringify(body);
  return request(app)
    .post(webhookPath)
    .set("Content-Type", "application/json")
    .set("PayBridge-Signature", signatureHeader(raw))
    .send(raw);
}

const paid = (code: Code, amount: number = BILL_TOTAL) => {
  doit.settle(code.providerRef, amount);
  return deliver(doit.eventFor(code.providerRef, "paid"));
};

type Row = { provider_refund_id: string; amount_idr: string };
const providerRows = async (intentId: string): Promise<Row[]> => {
  const { rows } = await owner.query<Row>(
    `SELECT provider_refund_id, amount_idr::text AS amount_idr
       FROM payment_provider_refunds
      WHERE tenant_id = $1 AND payment_intent_id = $2 ORDER BY provider_refund_id`,
    [tenantId, intentId],
  );
  return rows;
};
const providerSum = async (intentId: string) =>
  (await providerRows(intentId)).reduce((n, r) => n + Number(r.amount_idr), 0);

/** The payment door of a provider-initiated refund (967): handled in-request. */
function deliverRefund(code: Code, providerRefundId: string, amount: number) {
  return deliver({
    id: `evt_${randomBytes(8).toString("hex")}`,
    type: "payment.refunded",
    created_at: new Date().toISOString(),
    data: {
      payment_id: code.providerRef,
      refund_id: providerRefundId,
      amount,
      status: amount >= BILL_TOTAL ? "refunded" : "partially_refunded",
    },
  });
}

/** The recorder's row for OUR refund of the whole payment. */
async function seedOwnRow(code: Code, amountIdr: number) {
  await owner.query(
    `INSERT INTO payment_provider_refunds
       (id, tenant_id, outlet_id, payment_intent_id, provider, provider_refund_id,
        provider_payment_ref, amount_idr, source)
     VALUES ($1, $2, $3, $4, 'doit', $5, $6, $7, 'refund_webhook')`,
    [
      randomUUID(),
      tenantId,
      outletId,
      code.id,
      `payment:${code.providerRef}`,
      code.providerRef,
      amountIdr,
    ],
  );
}

describe("1025c-a a provider refund id starting with hold: follows the normal duplicate rule", () => {
  it("1025c-a-01 control: a provider refund 'hold:x' of a paid payment with nothing recorded is written once", async () => {
    const code = await newCode();
    expect((await paid(code)).status).toBeLessThan(500);

    const answer = await deliverRefund(code, "hold:x", 40_000);
    expect(answer.status, JSON.stringify(answer.body)).toBeLessThan(500);

    expect(await providerRows(code.id)).toEqual([
      { provider_refund_id: "hold:x", amount_idr: "40000" },
    ]);
  });

  it.each(["hold:x", "rf_plain_id"])(
    "1025c-a-02 payment:<ref> row of the whole payment exists, provider refund '%s' of the whole payment arrives: no second row",
    async (providerRefundId) => {
      const code = await newCode();
      expect((await paid(code)).status).toBeLessThan(500);
      await seedOwnRow(code, BILL_TOTAL);

      const answer = await deliverRefund(code, providerRefundId, BILL_TOTAL);
      expect(answer.status, JSON.stringify(answer.body)).toBeLessThan(500);

      expect(await providerRows(code.id), "no second row").toHaveLength(1);
      expect(await providerSum(code.id)).toBe(BILL_TOTAL);
    },
  );
});
